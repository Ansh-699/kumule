#!/usr/bin/env node
// Turns Prisma's from-empty DDL into an idempotent bootstrap script.
//
// Why this exists: the live database drifted from schema.prisma. It had users/wallets/
// nfts/escrows/transactions (with data) and was missing everything else, so 7 endpoint
// groups returned "table does not exist". `prisma migrate deploy` could not repair it
// (no _prisma_migrations baseline) and `migrate dev`/`reset` would drop live rows.
//
// The output is safe to run repeatedly against a database in ANY state: it creates what
// is missing, adds columns that are missing, and never drops or rewrites anything.
//
// Usage: node prisma/build-bootstrap.mjs > prisma/bootstrap.sql
//   (regenerate whenever schema.prisma changes)

import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const prismaBin = join(here, '..', 'node_modules', '.bin', 'prisma')

const ddl = execFileSync(prismaBin, [
  'migrate', 'diff',
  '--from-empty',
  '--to-schema-datamodel', join(here, 'schema.prisma'),
  '--script',
], { encoding: 'utf8' })

// A NOT NULL column cannot be added to a table that already has rows unless it has a
// default. Prisma omits defaults for @updatedAt and required scalars, so infer one;
// it only ever applies to a pre-existing populated table, never to a fresh CREATE.
const backfillDefault = (type) => {
  if (/^TIMESTAMP/i.test(type)) return 'CURRENT_TIMESTAMP'
  if (/^(DECIMAL|DOUBLE|INTEGER|BIGINT|SERIAL)/i.test(type)) return '0'
  if (/^BOOLEAN/i.test(type)) return 'false'
  if (/^(TEXT|VARCHAR|CHAR)/i.test(type)) return "''"
  if (/^JSONB?/i.test(type)) return "'{}'"
  return null
}

const out = [
  '-- GENERATED by prisma/build-bootstrap.mjs - do not edit by hand.',
  '-- Idempotent: creates missing tables/columns/indexes/foreign keys, drops nothing.',
  '-- Apply with: node prisma/apply-bootstrap.mjs',
  '',
  'BEGIN;',
  '',
]

const tableRe = /CREATE TABLE "([^"]+)" \(([\s\S]*?)\n\);/g
for (const [, table, body] of ddl.matchAll(tableRe)) {
  out.push(`-- ${table}`)
  out.push(`CREATE TABLE IF NOT EXISTS "${table}" (${body}\n);`)

  for (const rawLine of body.split('\n')) {
    const line = rawLine.trim().replace(/,$/, '')
    if (!line || line.startsWith('CONSTRAINT')) continue

    const m = line.match(/^"([^"]+)"\s+(.*)$/)
    if (!m) continue
    const [, column, rest] = m

    let spec = rest
    if (/NOT NULL/i.test(spec) && !/DEFAULT/i.test(spec)) {
      const type = spec.replace(/\s*NOT NULL.*$/i, '').trim()
      const dflt = backfillDefault(type)
      // No sensible default => add it nullable so the statement cannot fail on a
      // populated table. Flagged in the summary at the end of this file.
      spec = dflt ? `${type} NOT NULL DEFAULT ${dflt}` : type
    }
    out.push(`ALTER TABLE "${table}" ADD COLUMN IF NOT EXISTS "${column}" ${spec};`)
  }
  out.push('')
}

for (const line of ddl.split('\n')) {
  const t = line.trim()
  if (/^CREATE (UNIQUE )?INDEX /.test(t)) {
    out.push(t.replace(/^CREATE (UNIQUE )?INDEX /, (_, u) => `CREATE ${u || ''}INDEX IF NOT EXISTS `))
  }
}
out.push('')

// Postgres has no ADD CONSTRAINT IF NOT EXISTS, so guard on the catalog.
for (const line of ddl.split('\n')) {
  const m = line.trim().match(/^ALTER TABLE "([^"]+)" ADD CONSTRAINT "([^"]+)" (FOREIGN KEY[\s\S]*);$/)
  if (!m) continue
  const [, table, name, def] = m
  out.push(
    `DO $$ BEGIN`,
    `  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = '${name}') THEN`,
    `    ALTER TABLE "${table}" ADD CONSTRAINT "${name}" ${def};`,
    `  END IF;`,
    `END $$;`,
  )
}

out.push('', 'COMMIT;', '')
process.stdout.write(out.join('\n'))
